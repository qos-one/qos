"""
Strategy registry (step 19): 5 built-in strategies + external packages in $QOS_HOME/strategies (see qos/paths.py)

Package layout:  <name>@<version>/strategy.py  (+ manifest.json generated by the registry, + other package files)
- rescans the folder on every query (1-second throttle) · strategy.py changed (mtime/size) → manifest is re-read
- manifests are read in a subprocess (python -I -m qos.sdk._inspect) → third-party code never enters the API process · result stored in manifest.json
- the real class is loaded (imported) only when build_strategy needs it (node process / backtest), cached by mtime
- references: "name" = latest package version (no package → built-in strategy) · "name@1.2.0" = that version · "name@builtin" = built-in
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import os
import re
import subprocess
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILTIN = "builtin"
PKG_RE = re.compile(r"^([a-z][a-z0-9_]{1,31})@(\d+\.\d+\.\d+)$")
SCAN_INTERVAL_S = 1.0
MANIFEST_FILE = "manifest.json"


def strategies_dir() -> Path:
    from qos import paths
    return paths.strategies_dir()


def split_ref(ref: str) -> tuple[str, str | None]:
    """'ema_cross@1.2.0' → ('ema_cross', '1.2.0') · 'ema_cross' → ('ema_cross', None)"""
    name, _, ver = str(ref).partition("@")
    return name, (ver or None)


def version_key(v: str) -> tuple:
    return tuple(int(x) for x in v.split(".")) if re.match(r"^\d+(\.\d+)*$", v) else (-1,)


@dataclass
class Entry:
    name: str
    version: str                       # "1.0.0" or "builtin"
    kind: str                          # "package" | "builtin"
    path: Path | None = None           # package folder
    manifest: dict = field(default_factory=dict)
    status: str = "ok"                 # ok | error
    error: str = ""
    source_sig: str = ""               # mtime:size of strategy.py
    module: object = None              # module-like (NAME/LABEL/PARAMS/GRID/summary/Config/Strategy) once loaded
    _module_sig: str = ""

    @property
    def ref(self) -> str:
        return f"{self.name}@{self.version}"

    def spec(self) -> dict:
        m = self.manifest
        return {"label": m.get("label", self.name), "params": m.get("params", []), "grid": m.get("grid", {}),
                "doc": m.get("description") or m.get("label", self.name), "sdk": self.kind == "package" or bool(m.get("sdk")),
                "version": self.version, "kind": self.kind, "status": self.status, "error": self.error,
                "instruments": m.get("instruments", []), "timeframe": m.get("timeframe"), "requires": m.get("requires", [])}


class Registry:
    def __init__(self):
        self.builtins: dict[str, Entry] = {}
        self.packages: dict[str, Entry] = {}        # ref → Entry
        self._last_scan = 0.0
        self._dir_sig = ""

    # ---------- builtin ----------
    def add_builtin(self, module) -> Entry:
        m = {"name": module.NAME, "label": module.LABEL, "version": BUILTIN, "params": module.PARAMS, "grid": module.GRID,
             "description": (module.__doc__ or "").strip().splitlines()[0] if module.__doc__ else module.LABEL,
             "sdk": hasattr(module, "SDK_CLASS")}
        e = Entry(module.NAME, BUILTIN, "builtin", manifest=m, module=module)
        self.builtins[module.NAME] = e
        return e

    # ---------- scan ----------
    def _source_sig(self, d: Path) -> str:
        f = d / "strategy.py"
        try:
            st = f.stat()
        except FileNotFoundError:
            return ""
        return f"{st.st_mtime_ns}:{st.st_size}"

    def scan(self, force: bool = False) -> None:
        now = time.time()
        if not force and now - self._last_scan < SCAN_INTERVAL_S:
            return
        self._last_scan = now
        base = strategies_dir()
        found: dict[str, Entry] = {}
        if base.exists():
            for d in sorted(base.iterdir()):
                m = PKG_RE.match(d.name)
                if not d.is_dir() or not m:
                    continue
                name, ver = m.group(1), m.group(2)
                ref = f"{name}@{ver}"
                sig = self._source_sig(d)
                old = self.packages.get(ref)
                if old is not None and old.source_sig == sig and sig and old.path == d:
                    found[ref] = old
                    continue
                found[ref] = self._inspect(name, ver, d, sig)
        self.packages = found

    def _inspect(self, name: str, ver: str, d: Path, sig: str) -> Entry:
        e = Entry(name, ver, "package", path=d, source_sig=sig)
        if not sig:
            e.status, e.error = "error", "strategy.py not found"
            return e
        mf = d / MANIFEST_FILE
        try:
            cached = json.loads(mf.read_text())
            if cached.get("source_sig") == sig and cached.get("ok") is not None:
                return self._apply(e, cached)
        except Exception:
            pass
        res = self._run_inspect(d / "strategy.py")
        res["source_sig"] = sig
        res["inspected_at"] = time.strftime("%Y-%m-%dT%H:%M:%S")
        try:
            mf.write_text(json.dumps(res, indent=2, default=str))
        except OSError:
            pass
        return self._apply(e, res)

    def _apply(self, e: Entry, res: dict) -> Entry:
        if res.get("ok"):
            m = dict(res["manifest"])
            if m.get("name") != e.name:
                e.status, e.error = "error", f"class name='{m.get('name')}' does not match folder '{e.name}'"
                return e
            if m.get("version") != e.version:
                e.status, e.error = "error", f"class version='{m.get('version')}' does not match folder '{e.version}'"
                return e
            e.manifest = m
        else:
            e.status, e.error = "error", str(res.get("error") or "unknown error")[:500]
        return e

    def check_config(self, cfg: dict, source: str = "EXTERNAL") -> None:
        """Validate a config by building the real Strategy — built-ins in this process, packages in a subprocess (third-party code stays out of the API)"""
        e = self.resolve(cfg.get("strategy", "ema_cross"))
        if e.kind == "builtin":
            m = e.module
            m.Strategy(config=m.Config.from_dict(cfg, source=source, params=m.PARAMS))
            return
        if e.status != "ok":
            raise ValueError(f"strategy '{e.ref}' cannot be loaded: {e.error}")
        res = self._run_inspect(e.path / "strategy.py", check={**cfg, "_source": source})
        if not res.get("ok"):
            raise ValueError(f"{e.ref}: {res.get('error', 'invalid config')}")

    @staticmethod
    def _run_inspect(path: Path, check: dict | None = None) -> dict:
        pkg = path.parent if path.suffix == ".py" else path
        cmd = [venv_python(pkg) or sys.executable, "-I", str(ROOT / "qos" / "sdk" / "_inspect.py")]       # packages with requires use their own venv
        cmd += ["--check", str(path), json.dumps(check, default=str)] if check is not None else [str(path)]
        try:
            p = subprocess.run(cmd, cwd=str(ROOT), capture_output=True, text=True, timeout=60)
        except subprocess.TimeoutExpired:
            return {"ok": False, "error": "inspect timed out (60 s) — strategy.py must not block on import"}
        out = (p.stdout or "").strip().splitlines()
        try:
            return json.loads(out[-1]) if out else {"ok": False, "error": (p.stderr or "no output")[-500:]}
        except json.JSONDecodeError:
            return {"ok": False, "error": ((p.stderr or "") + (p.stdout or ""))[-500:]}

    # ---------- lookup ----------
    def versions(self, name: str) -> list[Entry]:
        self.scan()
        return sorted((e for e in self.packages.values() if e.name == name), key=lambda e: version_key(e.version))

    def resolve(self, ref: str) -> Entry:
        self.scan()
        name, ver = split_ref(ref)
        if ver == BUILTIN:
            if name in self.builtins:
                return self.builtins[name]
            raise ValueError(f"no builtin strategy '{name}'")
        if ver:
            e = self.packages.get(f"{name}@{ver}")
            if e is None:
                raise ValueError(f"strategy package '{name}@{ver}' not found in {strategies_dir()}")
            return e
        ok = [e for e in self.versions(name) if e.status == "ok"]
        if ok:
            return ok[-1]
        if name in self.builtins:
            return self.builtins[name]
        bad = self.versions(name)
        if bad:
            raise ValueError(f"strategy '{name}' has no loadable version: {bad[-1].error}")
        raise ValueError(f"unknown strategy '{name}' (have: {', '.join(self.names())})")

    def names(self) -> list[str]:
        self.scan()
        return sorted(set(self.builtins) | {e.name for e in self.packages.values()})

    def entries(self) -> list[Entry]:
        self.scan()
        return list(self.builtins.values()) + sorted(self.packages.values(), key=lambda e: (e.name, version_key(e.version)))

    def specs(self) -> dict[str, dict]:
        """name → spec of the version 'name' resolves to (including all versions of that name)"""
        out: dict[str, dict] = {}
        for name in self.names():
            try:
                e = self.resolve(name)
                out[name] = {**e.spec(), "versions": [v.version for v in self.versions(name)]}
            except ValueError as ex:
                out[name] = {"label": name, "params": [], "grid": {}, "doc": "", "sdk": True, "version": None, "kind": "package",
                             "status": "error", "error": str(ex), "versions": [v.version for v in self.versions(name)]}
        return out

    # ---------- load ----------
    def load(self, ref: str):
        """Return the module-like object build_strategy uses (imports package code into this process)"""
        e = self.resolve(ref)
        if e.kind == "builtin":
            return e.module
        if e.status != "ok":
            raise ValueError(f"strategy '{e.ref}' cannot be loaded: {e.error}")
        if e.module is not None and e._module_sig == e.source_sig:
            return e.module
        from qos.sdk import Strategy, compile
        path = e.path / "strategy.py"
        modname = "qos_pkg_" + hashlib.sha1(str(path).encode()).hexdigest()[:12] + "_" + e.source_sig.replace(":", "_")
        spec = importlib.util.spec_from_file_location(modname, path)
        mod = importlib.util.module_from_spec(spec)
        sys.modules[modname] = mod
        prev = sys.dont_write_bytecode
        sys.dont_write_bytecode = True                   # do not write __pycache__ into the package folder
        try:
            spec.loader.exec_module(mod)
        finally:
            sys.dont_write_bytecode = prev
        classes = [v for v in vars(mod).values() if isinstance(v, type) and issubclass(v, Strategy) and v is not Strategy and v.__module__ == mod.__name__]
        if len(classes) != 1:
            raise ValueError(f"{e.ref}: strategy.py must define exactly one qos.sdk.Strategy subclass")
        e.module = compile(classes[0])
        e._module_sig = e.source_sig
        return e.module


def venv_python(pkg_dir) -> str | None:
    """Python of the package's own venv (step 22: created when the manifest has requires) · None = use the main env"""
    if not pkg_dir:
        return None
    for rel in ("bin/python", "Scripts/python.exe"):
        p = Path(pkg_dir) / ".venv" / rel
        if p.exists():
            return str(p)
    return None


REG = Registry()


def write_package(cls, base: Path | None = None, source: str | None = None) -> Path:
    """Create a package folder from an SDK class (used when migrating built-in strategies and by qos new) · source = strategy.py text"""
    import inspect

    from qos.sdk import validate
    errs = validate(cls)
    if errs:
        raise ValueError("; ".join(errs))
    d = (base or strategies_dir()) / f"{cls.name}@{cls.version}"
    d.mkdir(parents=True, exist_ok=True)
    (d / "strategy.py").write_text(source if source is not None else inspect.getsource(sys.modules[cls.__module__]))
    return d
